"""Measure the separate Alt-Mitte resident inventory and verify glazing in its drawn companion tiles."""
import argparse
import base64
from collections import defaultdict
import gzip
import hashlib
import json
from pathlib import Path

import numpy as np
from shapely import make_valid, points, distance, union_all
from shapely.geometry import Polygon

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "src/app/src/data"
TILES = ROOT / "src/app/public/mesh/surrounding-berlin-v159"
GEO = ROOT / "geo_data/regierungsviertel"
FLOOR = 175_000
# The four vertical directions in build_alt_mitte_v169.isometric_shading, applied
# to its original GLASS sRGB swatch (82,108,115) and packed as linear RGB8.
PANE_COLOURS = [(21, 37, 43), (20, 35, 41), (19, 34, 39), (20, 36, 41)]


def digest(blob):
    return hashlib.sha256(blob).hexdigest()


def pane_centres(packet):
    """Find full undistorted 1.25 × 1.79 m windows generated by v169 on actual wall planes."""
    centres = []
    for mesh in packet["meshes"]:
        if mesh["kind"] != "alt-mitte-v169":
            continue
        xyz = np.frombuffer(base64.b64decode(mesh["positions"]), "<u2").reshape(-1, 3).astype(float) / 100
        xyz += np.asarray(packet["origin"])
        indices = np.frombuffer(base64.b64decode(mesh["indices"]), "<u4").reshape(-1, 3)
        colours = np.frombuffer(base64.b64decode(mesh["colors"]), "u1").reshape(-1, 3)
        glazing = np.zeros(len(colours), dtype=bool)
        for swatch in PANE_COLOURS:
            glazing |= np.all(colours == swatch, axis=1)
        triangles = xyz[indices[np.all(glazing[indices], axis=1)]]
        height = np.ptp(triangles[:, :, 1], axis=1)
        candidates = triangles[np.abs(height - 1.79) < .011]
        xz = candidates[:, :, [0, 2]]
        edges = np.linalg.norm(xz - np.roll(xz, 1, axis=1), axis=2)
        # One vertical edge and two full-width edges make up a pane half.
        edge = np.sort(edges, axis=1)
        candidates = candidates[(edge[:, 0] < .015) & (np.abs(edge[:, 1] - 1.25) < .016) & (np.abs(edge[:, 2] - 1.25) < .016)]
        centres.extend((candidates.min(axis=1) + candidates.max(axis=1)) / 2)
    return np.asarray(centres).reshape(-1, 3)


def audit(historic):
    historical_bytes = historic.read_bytes()
    legacy = {r["id"]: r for r in json.loads(historical_bytes)["buildings"]}
    sources = {}
    families = defaultdict(list)
    for suffix in ("001", "002"):
        path = DATA / f"altMitteV169Navigation/packet-{suffix}.json"
        raw = path.read_bytes()
        sources[path.relative_to(ROOT).as_posix()] = digest(raw)
        for part in json.loads(raw):
            surface = make_valid(Polygon(part["ring"], part["holes"]))
            families[part["sourceId"]].append((part["groundY"], part["topY"], surface))
    roster = DATA / "altMitteDrawnV169Source.json"
    assert set(families) == set(json.loads(roster.read_bytes())["sourceParents"])
    manifest = json.loads((TILES / "manifest.json").read_bytes())
    tiles = {}
    selected = []
    for key, parts in families.items():
        upper = sum((high - low) * shape.area for low, high, shape in parts)
        if upper < FLOOR:
            continue
        elevations = sorted({y for low, high, _ in parts for y in (low, high)})
        volume = sum((b - a) * union_all([shape for low, high, shape in parts if low <= a and b <= high]).area
                     for a, b in zip(elevations, elevations[1:]))
        if volume < FLOOR:
            continue
        west, north, east, south = union_all([shape for _, _, shape in parts]).bounds
        matches = {}
        for tile in manifest["chunks"]:
            x0, z0, x1, z1 = tile["bounds"]
            if east + 1 < x0 or south + 1 < z0 or west - 1 > x1 or north - 1 > z1:
                continue
            descriptor = tile["drawn"]
            if tile["id"] not in tiles:
                payload = (TILES / descriptor["url"]).read_bytes()
                assert digest(payload) == descriptor["sha256"]
                tiles[tile["id"]] = pane_centres(json.loads(gzip.decompress(payload)))
            candidates = tiles[tile["id"]]
            if not len(candidates):
                continue
            mask = ((candidates[:, 0] >= west - .5) & (candidates[:, 0] <= east + .5) &
                    (candidates[:, 2] >= north - .5) & (candidates[:, 2] <= south + .5))
            candidates = candidates[mask]
            if not len(candidates):
                continue
            wall_xz = points(candidates[:, 0], candidates[:, 2])
            keep = np.zeros(len(candidates), dtype=bool)
            for low, high, shape in parts:
                # At the source window plane, including centimetre quantization
                # and small offsets between the roof projection and facade base.
                keep |= ((candidates[:, 1] > low + 1) & (candidates[:, 1] < high - .5) &
                         (distance(shape.boundary, wall_xz) <= .35))
            if keep.any():
                panes = candidates[keep]
                locations = np.unique(np.rint(panes * 200).astype(int), axis=0)
                matches[tile["id"]] = {"paneCentres": len(locations), "packetSha256": descriptor["sha256"]}
        entry = {
            "id": key, "volumeM3": round(volume, 2), "parts": len(parts),
            "historicalFacadeTriangles": legacy[key]["facadeTriangles"],
            "paneCentres": sum(m["paneCentres"] for m in matches.values()),
            "tiles": matches,
        }
        if entry["paneCentres"] < 2 or entry["historicalFacadeTriangles"] < 4:
            raise ValueError(f"Unresolved Alt-Mitte source {key}")
        selected.append(entry)
    return {
        "schemaVersion": 1, "floorM3": FLOOR, "sourceHashes": sources,
        "historicalRenderAuditSha256": digest(historical_bytes),
        "residentFamilies": len(families), "parts": sum(map(len, families.values())),
        "method": "Union of footprint polygons by occupied height interval. Roof volume uses the same prism-layer metric as the city ranking. Verify independently identifiable 1.25 × 1.79 m glazing triangles, rounded per pane centre, against the current four glazing colours, the package and vertical range of each source wall.",
        "rows": sorted(selected, key=lambda r: (-r["volumeM3"], r["id"])),
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--historic-audit", type=Path, default=GEO / "alt-mitte-v169/render-audit.json")
    parser.add_argument("--output", type=Path, default=GEO / "windowless-resident-audit-v377.json")
    args = parser.parse_args()
    run = audit(args.historic_audit)
    args.output.write_text(json.dumps(run, ensure_ascii=False, separators=(",", ":")) + "\n")
