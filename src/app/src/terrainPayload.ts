function shadeFor(
  shades: readonly number[],
  xIdx: number,
  zIdx: number,
  salt: number,
  output = new Color(),
): Color {
  const pick = Math.abs(xIdx * 31 + zIdx * 17 + salt * 7) % shades.length;
  return output.setHex(shades[pick]);
}


function voxelMaterial(emissive = 0x3d3d3d): MeshStandardMaterial {
  return new MeshStandardMaterial({
    color: 0xffffff,
    // A small neutral emissive floor lifts the shadow faces so block
    // colours stay readable all around, like Minecraft's flat light.
    // The drawn city passes 0 — its ground must not self-glow.
    emissive,
    flatShading: true,
    metalness: 0,
    roughness: 1,
  });
}


type InstanceWriter = {
  mesh: InstancedMesh;
  write: (
    center: Vector3,
    size: Vector3,
    color: Color,
    rotationY?: number,
  ) => void;
};


function instancedBoxes(
  name: string,
  count: number,
  emissive?: number,
  fullyWritten = false,
): InstanceWriter {
  const deferMatrices = fullyWritten && count > 0;
  const mesh = new InstancedMesh(
    new BoxGeometry(1, 1, 1),
    voxelMaterial(emissive),
    deferMatrices ? 0 : Math.max(1, count),
  );
  if (deferMatrices) allocateUnwrittenInstances(mesh, count);
  mesh.name = name;
  mesh.count = 0;
  const matrix = new Matrix4();
  return {
    mesh,
    write: (center, size, color, rotationY = 0) => {
      const index = mesh.count;
      if (rotationY === 0) {
        matrix.makeScale(size.x, size.y, size.z);
      } else {
        matrix.makeRotationY(rotationY);
        matrix.scale(size);
      }
      matrix.setPosition(center.x, center.y, center.z);
      mesh.setMatrixAt(index, matrix);
      mesh.setColorAt(index, color);
      mesh.count = index + 1;
    },
  };
}


// Only for private meshes whose complete capacity is written before publish.
function allocateUnwrittenInstances(mesh: InstancedMesh, count: number): void {
  mesh.instanceMatrix = new InstancedBufferAttribute(new Float32Array(count * 16), 16);
  mesh.instanceColor = new InstancedBufferAttribute(new Float32Array(count * 3), 3);
  mesh.count = count;
}


/**
 * Sample the payload's coarse interpolated terrain grid at grid offsets.
 */
export function groundTopSampler(
  payload: VoxelPayload,
): (xOffset: number, zOffset: number) => number {
  const heights = payload.ground_height;
  return (xOffset, zOffset) => {
    const col = Math.min(
      heights.cols - 1,
      Math.floor(xOffset / heights.stride_cells),
    );
    const row = Math.min(
      heights.rows - 1,
      Math.floor(zOffset / heights.stride_cells),
    );
    return (heights.y_dm[row * heights.cols + col] ?? 40) / 10;
  };
}


/**
 * Continuous counterpart to {@link groundTopSampler} for drawn surfaces.
 *
 * The committed height samples sit at the centres of 16 m terrain cells.
 * Nearest-cell lookup is correct for Minecraft blocks, but it made a road or
 * lawn jump vertically at every cell boundary. Bilinear interpolation keeps
 * the same measured samples and extrema while producing a continuous grade
 * for the isometric plates, kerbs and quay coping.
 */
export function smoothGroundTopSampler(
  payload: VoxelPayload,
): (xOffset: number, zOffset: number) => number {
  const heights = payload.ground_height;
  const valueAt = (col: number, row: number): number =>
    (heights.y_dm[row * heights.cols + col] ?? 40) / 10;
  return (xOffset, zOffset) => {
    const sampleX = xOffset / heights.stride_cells - 0.5;
    const sampleZ = zOffset / heights.stride_cells - 0.5;
    const rawCol = Math.floor(sampleX);
    const rawRow = Math.floor(sampleZ);
    const col0 = Math.max(0, Math.min(heights.cols - 1, rawCol));
    const row0 = Math.max(0, Math.min(heights.rows - 1, rawRow));
    const col1 = Math.max(0, Math.min(heights.cols - 1, rawCol + 1));
    const row1 = Math.max(0, Math.min(heights.rows - 1, rawRow + 1));
    const tx = col0 === col1 ? 0 : Math.max(0, Math.min(1, sampleX - rawCol));
    const tz = row0 === row1 ? 0 : Math.max(0, Math.min(1, sampleZ - rawRow));
    const north = valueAt(col0, row0) * (1 - tx) + valueAt(col1, row0) * tx;
    const south = valueAt(col0, row1) * (1 - tx) + valueAt(col1, row1) * tx;
    return north * (1 - tz) + south * tz;
  };
}


/**
 * World-coordinate ground sampler: metres in, terrain-top metres out,
 * null outside the surveyed grid.
 */
export function worldGroundSampler(
  payload: VoxelPayload,
): (x: number, z: number) => number | null {
  const sample = groundTopSampler(payload);
  const cell = payload.cell_m;
  const { cols, min_x_idx, min_z_idx, rows } = payload.grid;
  return (x, z) => {
    const xOffset = x / cell - min_x_idx;
    const zOffset = z / cell - min_z_idx;
    if (xOffset < 0 || zOffset < 0 || xOffset >= cols || zOffset >= rows) {
      return null;
    }
    return sample(xOffset, zOffset);
  };
}


/**
 * Build the run-length ground slabs as one InstancedMesh. Shared between
 * the Minecraft voxel world and the drawn isometric city (which reuses
 * the same surveyed ground/water/road classes with its own palette).
 */
export function createGroundSlabs(
  ...args: Parameters<typeof createGroundSlabsSteps>
): InstancedMesh {
  return finishSteps(createGroundSlabsSteps(...args));
}


function finishSteps<T>(steps: Generator<void, T>): T {
  let step = steps.next();
  while (!step.done) step = steps.next();
  return step.value;
}


function* createGroundSlabsSteps(
  payload: VoxelPayload,
  name: string,
  shadeMap: Record<string, readonly number[]>,
  options?: {
    bridgeDecks?: boolean;
    emissive?: number;
    skipClasses?: readonly string[];
    skipBridge?: boolean;
    skipBridgeAtWorld?: (x: number, z: number) => boolean;
    skipAtWorld?: (x: number, z: number) => boolean;
    skipWater?: boolean;
    /** Corrected core park only; other run transforms and paint remain exact. */
    parkRelief?: "drawn" | "native";
    /** Display grading only; canonical terrain samplers remain unchanged. */
    terrainOverride?: {
      bounds: { minX: number; maxX: number; minZ: number; maxZ: number };
      topAt: (x: number, z: number) => number | null;
    };
  },
): Generator<void, InstancedMesh> {
  const cell = payload.cell_m;
  const { min_x_idx, min_z_idx } = payload.grid;
  const worldXAbs = (xIdx: number, span = 1): number =>
    (xIdx + span / 2) * cell;
  const worldZAbs = (zIdx: number): number => (zIdx + 0.5) * cell;
  const groundTopY = groundTopSampler(payload);
  const skippedClasses = new Set(options?.skipClasses ?? []);
  // Grading keeps the original shared records; ordinary ground has no object list.
  const visibleRuns = options?.terrainOverride ? [] as GroundRun[] : new GroundRunBuffer();
  const appendRun = (classId: number, run: number, xStart: number, zOffset: number): void => {
    if (visibleRuns instanceof GroundRunBuffer) visibleRuns.push(classId, run, xStart, zOffset);
    else visibleRuns.push({ classId, run, xStart, zOffset });
  };
  let skippedByWorldPredicateCells = 0;
  let skippedBridgeCells = 0;
  for (let zOffset = 0; zOffset < payload.ground_rows.length; zOffset += 1) {
    if (zOffset % 16 === 0) yield;
    const row = payload.ground_rows[zOffset];
    for (const [xStart, run, classId] of row) {
      const className = payload.classes[classId] ?? "grass";
      if (
        skippedClasses.has(className) ||
        (options?.skipWater &&
          (className === "water" ||
            className === "basin" ||
            className === "pond")) ||
        (options?.skipBridge && className === "bridge")
      ) {
        continue;
      }
      const skipBridgeAtWorld =
        className === "bridge" ? options?.skipBridgeAtWorld : undefined;
      if (!options?.skipAtWorld && !skipBridgeAtWorld) {
        appendRun(classId, run, xStart, zOffset);
        continue;
      }
      let visibleStart = -1;
      for (let step = 0; step < run; step += 1) {
        const xOffset = xStart + step;
        const worldX = worldXAbs(min_x_idx + xOffset);
        const worldZ = worldZAbs(min_z_idx + zOffset);
        const hiddenByWorld = options?.skipAtWorld?.(worldX, worldZ) ?? false;
        const hiddenBridge = skipBridgeAtWorld?.(worldX, worldZ) ?? false;
        const hidden = hiddenByWorld || hiddenBridge;
        if (!hidden && visibleStart < 0) {
          visibleStart = xOffset;
        }
        if (hidden) {
          if (hiddenByWorld) skippedByWorldPredicateCells += 1;
          if (hiddenBridge) skippedBridgeCells += 1;
          if (visibleStart >= 0) {
            appendRun(classId, xOffset - visibleStart, visibleStart, zOffset);
            visibleStart = -1;
          }
        }
      }
      if (visibleStart >= 0) {
        appendRun(classId, xStart + run - visibleStart, visibleStart, zOffset);
      }
    }
  }
  // Only split runs touching the authored bank. In particular, never grade
  // water or change the sampling/colour of a run outside this bounded repair.
  const override = options?.terrainOverride;
  const gradedRuns: Array<{ classId: number; run: number; xStart: number;
    zOffset: number; topY?: number; shadeXStart?: number; shadeRun?: number }> = [];
  let gradedCells = 0;
  let gradedIndex = 0;
  // Ordinary city ground needs no second list of the same runs.
  for (const entry of Array.isArray(visibleRuns) ? visibleRuns : []) {
    if (gradedIndex++ % 512 === 0) yield;
    const { classId, xStart, run, zOffset } = entry;
    const className = payload.classes[classId];
    const z = worldZAbs(min_z_idx + zOffset);
    if (!override || ["water", "basin", "pond", "bridge"].includes(className) ||
        z < override.bounds.minZ || z > override.bounds.maxZ ||
        worldXAbs(min_x_idx + xStart + run - 1) < override.bounds.minX ||
        worldXAbs(min_x_idx + xStart) > override.bounds.maxX) {
      gradedRuns.push(entry);
      continue;
    }
    let ungradedStart = xStart;
    const originalTop = groundTopY(xStart + run / 2, zOffset);
    const originalShade = { shadeXStart: xStart, shadeRun: run };
    for (let xOffset = xStart; xOffset < xStart + run; xOffset++) {
      const x = worldXAbs(min_x_idx + xOffset);
      const topY = x >= override.bounds.minX && x <= override.bounds.maxX
        ? override.topAt(x, z) : null;
      if (topY === null) continue;
      if (xOffset > ungradedStart) gradedRuns.push({ ...entry, ...originalShade, xStart: ungradedStart, run: xOffset - ungradedStart, topY: originalTop });
      gradedRuns.push({ ...entry, ...originalShade, xStart: xOffset, run: 1, topY });
      ungradedStart = xOffset + 1;
      gradedCells++;
    }
    if (ungradedStart === xStart) gradedRuns.push(entry);
    else if (ungradedStart < xStart + run) gradedRuns.push({ ...entry, ...originalShade, xStart: ungradedStart, run: xStart + run - ungradedStart, topY: originalTop });
  }
  const finalRuns: GroundRunBuffer | typeof gradedRuns = override ? gradedRuns : visibleRuns;
  const reliefOptions = options?.parkRelief ? {
    cell, minXIndex: min_x_idx, minZIndex: min_z_idx,
    strideCells: payload.ground_height.stride_cells, mode: options.parkRelief,
    nearest: groundTopY, smooth: smoothGroundTopSampler(payload),
  } : null;
  const slicesFor = (classId: number, run: number, xStart: number, zOffset: number) =>
    reliefOptions && !["water", "pond", "basin", "bridge"].includes(payload.classes[classId])
      ? parkReliefGroundSlices(xStart, run, zOffset, reliefOptions) : null;
  let reliefExtra = 0;
  const countRelief = (classId: number, run: number, xStart: number, zOffset: number) => {
    const slices = slicesFor(classId, run, xStart, zOffset);
    if (slices) reliefExtra += slices.length - 1;
  };
  if (reliefOptions) {
    if (finalRuns instanceof GroundRunBuffer) finalRuns.forEach(countRelief);
    else for (const entry of finalRuns) countRelief(entry.classId, entry.run, entry.xStart, entry.zOffset);
  }
  const ground = instancedBoxes(name, finalRuns.length + reliefExtra, options?.emissive, true);
  ground.mesh.userData.parkReliefAdditionalRuns = reliefExtra;
  ground.mesh.userData.gradedPromenadeCells = gradedCells;
  ground.mesh.userData.skippedByWorldPredicateCells =
    skippedByWorldPredicateCells;
  ground.mesh.userData.skippedBridgeCells = skippedBridgeCells;
  const center = new Vector3();
  const size = new Vector3();
  const shade = new Color();
  const writeRun = (classId: number, run: number, xStart: number, zOffset: number,
    overriddenTop?: number, shadeXStart?: number, shadeRun?: number): void => {
    const className = payload.classes[classId] ?? "grass";
    const shades = shadeMap[className] ?? shadeMap.grass ?? FALLBACK_SHADES;
    const topY =
      className === "water"
        ? (payload.water_top_y_m ?? WATER_TOP_Y)
        : overriddenTop ?? groundTopY(xStart + run / 2, zOffset);
    // Real bridge decks (drawn city): a thin plate at bank level with
    // open air beneath, so the river visibly flows under the bridge
    // instead of the deck being ironed flat onto the water.
    const slabHeight =
      options?.bridgeDecks && className === "bridge" ? 1.1 : GROUND_SLAB_M;
    center.set(
      worldXAbs(min_x_idx + xStart, run),
      topY - slabHeight / 2,
      worldZAbs(min_z_idx + zOffset),
    );
    size.set(run * cell, slabHeight, cell);
    ground.write(center, size, shadeFor(shades, shadeXStart ?? xStart, zOffset, shadeRun ?? run, shade));
  };
  const writeWithRelief = (classId: number, run: number, xStart: number, zOffset: number,
    overriddenTop?: number, shadeXStart?: number, shadeRun?: number) => {
    const slices = slicesFor(classId, run, xStart, zOffset);
    if (!slices) { writeRun(classId, run, xStart, zOffset, overriddenTop, shadeXStart, shadeRun); return; }
    for (const slice of slices) writeRun(classId, slice.run, slice.xStart, zOffset,
      slice.topY, shadeXStart ?? xStart, shadeRun ?? run);
  };
  if (finalRuns instanceof GroundRunBuffer) finalRuns.forEach(writeWithRelief);
  else for (const entry of finalRuns) {
    writeWithRelief(entry.classId, entry.run, entry.xStart, entry.zOffset,
      entry.topY, entry.shadeXStart, entry.shadeRun);
  }
  return ground.mesh;
}


type GatehouseGroundPoint = [number, number, number];

type GatehouseGroundPolygon = GatehouseGroundPoint[];

const gatehouseGroundCuts = GROSSER_STERN_GATEHOUSES_V164_GROUND_CUTS.map(ring => {
  const area = ring.reduce((sum,a,i) => { const b=ring[(i+1)%ring.length]; return sum+a[0]*b[1]-b[0]*a[1]; },0);
  const orientation = Math.sign(area);
  return { ring, minX:Math.min(...ring.map(p=>p[0])), maxX:Math.max(...ring.map(p=>p[0])),
    minZ:Math.min(...ring.map(p=>p[1])), maxZ:Math.max(...ring.map(p=>p[1])),
    planes:ring.map((a,i)=>{const b=ring[(i+1)%ring.length];return (p:GatehouseGroundPoint) => orientation*((b[0]-a[0])*(p[2]-a[1])-(b[1]-a[1])*(p[0]-a[0]));}) };
});

function gatehousePolygonArea(p: GatehouseGroundPolygon): number {
  if(p.length<3)return 0;
  // Relative coordinates avoid cancellation at the large metric city coordinates.
  const a=p[0];let sum=0;for(let i=1;i+1<p.length;i++)sum+=(p[i][0]-a[0])*(p[i+1][2]-a[2])-(p[i+1][0]-a[0])*(p[i][2]-a[2]);
  return Math.abs(sum)/2;
}

function clipGatehouseGroundPlane(poly:GatehouseGroundPolygon, distance:(p:GatehouseGroundPoint)=>number):GatehouseGroundPolygon {
  const result:GatehouseGroundPolygon=[];
  for(let i=0;i<poly.length;i++){
    const a=poly[i],b=poly[(i+1)%poly.length],da=distance(a),db=distance(b);
    if(da>=0)result.push(a);
    if((da>=0)!==(db>=0)){const t=da/(da-db);result.push([a[0]+(b[0]-a[0])*t,a[1]+(b[1]-a[1])*t,a[2]+(b[2]-a[2])*t]);}
  }
  return result;
}

/** Subtract only the four rotated interior stair wells, retaining height interpolation. */
function gatehouseGroundComplement(poly:GatehouseGroundPolygon):GatehouseGroundPolygon[]|null {
  const minX=Math.min(...poly.map(p=>p[0])),maxX=Math.max(...poly.map(p=>p[0]));
  const minZ=Math.min(...poly.map(p=>p[2])),maxZ=Math.max(...poly.map(p=>p[2]));
  let pieces=[poly],changed=false;
  for(const cut of gatehouseGroundCuts){
    if(maxX<=cut.minX||minX>=cut.maxX||maxZ<=cut.minZ||minZ>=cut.maxZ)continue;
    const next:GatehouseGroundPolygon[]=[];
    for(const piece of pieces){
      let inside=piece;for(const plane of cut.planes)inside=clipGatehouseGroundPlane(inside,plane);
      if(gatehousePolygonArea(inside)<1e-9){next.push(piece);continue;}
      changed=true;inside=piece;
      for(const plane of cut.planes){
        const outside=clipGatehouseGroundPlane(inside,p=>-plane(p));
        if(gatehousePolygonArea(outside)>1e-9)next.push(outside);
        inside=clipGatehouseGroundPlane(inside,plane);
        if(inside.length<3)break;
      }
    }
    pieces=next;
  }
  return changed?pieces:null;
}


/**
 * Exact triangle complement for draped park/path plates. Original indexed vertices
 * and all unaffected index triples are retained; only the few touched triangles
 * gain boundary vertices. This avoids expanding a whole city plate into triangle
 * soup or removing a four-metre ground cell around a narrow rotated stair well.
 */
export function cutGrosserSternGatehouseGroundSurface(source:BufferGeometry):BufferGeometry {
  const attribute=source.getAttribute("position"),p=attribute.array;
  const index=source.getIndex(),indices=index?.array,count=indices?.length??attribute.count;
  const changes=new Map<number,number[]>();let addedValues=0;
  for(let i=0;i<count;i+=3){
    const ia=(indices?indices[i]:i)*3,ib=(indices?indices[i+1]:i+1)*3,ic=(indices?indices[i+2]:i+2)*3;
    const minX=Math.min(p[ia],p[ib],p[ic]),maxX=Math.max(p[ia],p[ib],p[ic]);
    if(maxX < -1590 || minX > -1330)continue;
    const minZ=Math.min(p[ia+2],p[ib+2],p[ic+2]),maxZ=Math.max(p[ia+2],p[ib+2],p[ic+2]);
    if(maxZ < 399 || minZ > 512 || !gatehouseGroundCuts.some(c=>maxX>c.minX&&minX<c.maxX&&maxZ>c.minZ&&minZ<c.maxZ))continue;
    const pieces=gatehouseGroundComplement([[p[ia],p[ia+1],p[ia+2]],[p[ib],p[ib+1],p[ib+2]],[p[ic],p[ic+1],p[ic+2]]]);
    if(!pieces)continue;
    const replacement:number[]=[];
    for(const piece of pieces)for(let j=1;j+1<piece.length;j++)if(gatehousePolygonArea([piece[0],piece[j],piece[j+1]])>1e-9)replacement.push(...piece[0],...piece[j],...piece[j+1]);
    changes.set(i,replacement);addedValues+=replacement.length;
  }
  if(!changes.size)return source;
  const positions=new Float32Array(p.length+addedValues);positions.set(p);
  const IndexArray=positions.length/3>65535?Uint32Array:Uint16Array;
  const outputIndices=new IndexArray(count-changes.size*3+addedValues/3);let added=p.length,cursor=0;
  for(let i=0;i<count;i+=3){
    const replacement=changes.get(i);
    if(replacement===undefined){outputIndices[cursor++]=indices?indices[i]:i;outputIndices[cursor++]=indices?indices[i+1]:i+1;outputIndices[cursor++]=indices?indices[i+2]:i+2;continue;}
    positions.set(replacement,added);for(let k=0;k<replacement.length;k+=3)outputIndices[cursor++]=(added+k)/3;added+=replacement.length;
  }
  const geometry=new BufferGeometry();geometry.setAttribute("position",new Float32BufferAttribute(positions,3));geometry.setIndex(new BufferAttribute(outputIndices,1));
  geometry.userData={...source.userData,gatehouseGroundApertures:true,gatehouseChangedTriangles:changes.size};
  geometry.computeBoundingBox();geometry.computeBoundingSphere();return geometry;
}


/**
 * Preserve each original terrain run's exact colour, top and bottom outside the
 * small rotated wells. Removed instances are replaced by their full extruded
 * complement; previously authored ground exclusions and unrelated children stay.
 */
export function restoreGrosserSternGatehouseGroundOwnership(slabs:InstancedMesh):void {
  const oldMatrices=slabs.instanceMatrix.array,oldColors=slabs.instanceColor?.array;
  const changed=new Map<number,GatehouseGroundPolygon[]>();
  for(let i=0;i<slabs.count;i++){
    const m=i*16,x=oldMatrices[m+12],z=oldMatrices[m+14],hx=oldMatrices[m]/2,hz=oldMatrices[m+10]/2;
    if(x+hx< -1590||x-hx> -1330||z+hz<399||z-hz>512)continue;
    const y=oldMatrices[m+13]+oldMatrices[m+5]/2;
    const pieces=gatehouseGroundComplement([[x-hx,y,z-hz],[x+hx,y,z-hz],[x+hx,y,z+hz],[x-hx,y,z+hz]]);
    if(pieces)changed.set(i,pieces);
  }
  if(!changed.size)return;
  const matrices=new Float32Array((slabs.count-changed.size)*16),colors=oldColors?new Float32Array((slabs.count-changed.size)*3):null;
  const positions:number[]=[],paints:number[]=[];let cursor=0;
  for(let i=0;i<slabs.count;i++){
    const pieces=changed.get(i);
    if(!pieces){matrices.set(oldMatrices.subarray(i*16,i*16+16),cursor*16);if(colors&&oldColors)colors.set(oldColors.subarray(i*3,i*3+3),cursor*3);cursor++;continue;}
    const bottom=oldMatrices[i*16+13]-oldMatrices[i*16+5]/2,color=oldColors?oldColors.subarray(i*3,i*3+3):[1,1,1];
    const triangle=(a:GatehouseGroundPoint,b:GatehouseGroundPoint,c:GatehouseGroundPoint):void=>{positions.push(...a,...b,...c);paints.push(...color,...color,...color);};
    for(const piece of pieces){
      for(let j=1;j+1<piece.length;j++){
        triangle(piece[0],piece[j+1],piece[j]);
        triangle([piece[0][0],bottom,piece[0][2]],[piece[j][0],bottom,piece[j][2]],[piece[j+1][0],bottom,piece[j+1][2]]);
      }
      for(let j=0;j<piece.length;j++){
        const a=piece[j],b=piece[(j+1)%piece.length],aa:GatehouseGroundPoint=[a[0],bottom,a[2]],bb:GatehouseGroundPoint=[b[0],bottom,b[2]];
        triangle(a,b,bb);triangle(a,bb,aa);
      }
    }
  }
  slabs.instanceMatrix=new InstancedBufferAttribute(matrices,16);if(colors)slabs.instanceColor=new InstancedBufferAttribute(colors,3);slabs.count=cursor;slabs.boundingBox=null;slabs.boundingSphere=null;
  const sourceMaterial=Array.isArray(slabs.material)?slabs.material[0]:slabs.material;
  const day=(slabs.userData.dayMaterial??sourceMaterial).clone() as MeshBasicMaterial;
  const night=(slabs.userData.nightMaterial??sourceMaterial).clone() as MeshBasicMaterial;
  day.vertexColors=true;night.vertexColors=true;day.side=DoubleSide;night.side=DoubleSide;
  const geometry=new BufferGeometry();geometry.setAttribute("position",new Float32BufferAttribute(positions,3));geometry.setAttribute("color",new Float32BufferAttribute(paints,3));geometry.computeVertexNormals();geometry.computeBoundingBox();geometry.computeBoundingSphere();
  const mesh=new Mesh(geometry,day);mesh.name="Exact terrain complements outside four Grosser Stern stair wells";
  mesh.userData={dayMaterial:day,nightMaterial:night,gatehouseGroundOwnership:true,affectedRuns:changed.size,textureFree:true};
  slabs.add(freezeStaticSceneTransforms(mesh));
}
