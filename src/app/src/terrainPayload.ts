/**
 * True voxel world for the Minecraft mode: the city as axis-aligned
 * blocks generated by `isometric_berlin.generation.build_minecraft_voxels`
 * from surveyed LoD2 footprints + measured heights, OSM water/roads and
 * the official tree points. Rendered as a handful of InstancedMeshes
 * (one box per building column / ground run / tree part) so the whole
 * world stays at a few draw calls and well below photogrammetry-tier
 * triangle counts — deliberately "eckig, klotzig, blockig".
 */
export type VoxelPayload = {
  schema_version: number;
  cell_m: number;
  classes: string[];
  grid: { cols: number; min_x_idx: number; min_z_idx: number; rows: number };
  /** Coarse ground-top heights in decimetres, row-major at stride_cells. */
  ground_height: {
    cols: number;
    rows: number;
    stride_cells: number;
    y_dm: number[];
  };
  /** rows[z_offset] = [x_start_offset, run_length, classId][] (grid offsets). */
  ground_rows: Array<Array<[number, number, number]>>;
  /** Legacy schema 1: absolute [x_idx, z_idx, y0_dm, y1_dm, classId]. */
  buildings?: VoxelBuildingColumn[];
  /** Schema 2: rows[z_offset] = [x_offset, run, y0_dm, y1_dm, classId][]. */
  building_rows?: Array<Array<[number, number, number, number, number]>>;
  /** Legacy schema 1: absolute [x_idx, z_idx, y0_dm, height_dm]. */
  trees?: VoxelTreeBlock[];
  /** Schema 2: rows[z_offset] = [x_offset, y0_dm, height_dm][]. */
  tree_rows?: Array<Array<[number, number, number]>>;
  water_top_y_m: number;
};


export type MinecraftVoxelDetailProfile = "full" | "mobile";


export type VoxelBuildingColumn = [number, number, number, number, number];

export type VoxelTreeBlock = [number, number, number, number];


/** Visit compact tree rows without allocating the expanded 25k-entry array. */
export function forEachVoxelTreeBlock(
  payload: VoxelPayload,
  visit: (
    xIndex: number,
    zIndex: number,
    y0dm: number,
    heightDm: number,
  ) => void,
): void {
  if (!payload.tree_rows) {
    for (const [xIndex, zIndex, y0dm, heightDm] of payload.trees ?? []) {
      visit(xIndex, zIndex, y0dm, heightDm);
    }
    return;
  }
  payload.tree_rows.forEach((row, zOffset) => {
    for (const [xOffset, y0dm, heightDm] of row) {
      visit(
        payload.grid.min_x_idx + xOffset,
        payload.grid.min_z_idx + zOffset,
        y0dm,
        heightDm,
      );
    }
  });
}


export const MINECRAFT_TREE_RETENTION = Object.freeze({
  full: Object.freeze({
    keptBuckets: 2, modulo: 3, thinningBuckets: 4, thinningModulo: 6,
  }),
  mobile: Object.freeze({
    keptBuckets: 1, modulo: 3, thinningBuckets: 4, thinningModulo: 6,
  }),
});


/**
 * Keep four of the five secondary buckets used through v1.0.26: about 20%
 * fewer existing generic trees in both profiles. Reducing the same bucket
 * threshold cannot reintroduce previously absent trees, and mobile remains
 * a stable subset of full. Source tree data is untouched.
 */
export function minecraftVoxelTreeRetained(
  xIndex: number,
  zIndex: number,
  detailProfile: MinecraftVoxelDetailProfile,
): boolean {
  const policy = MINECRAFT_TREE_RETENTION[detailProfile];
  const hash =
    (Math.imul(xIndex, 73_856_093) ^ Math.imul(zIndex, 19_349_663)) >>> 0;
  return (
    hash % policy.modulo < policy.keptBuckets &&
    Math.floor(hash / policy.modulo) % policy.thinningModulo < policy.thinningBuckets
  );
}


