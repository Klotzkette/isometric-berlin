export type PotsdamerPanoramaMaterial = Readonly<{ facade: number; roof: number }>;
const materials = new Map<string, PotsdamerPanoramaMaterial>();
for (const building of POTSDAMER_PANORAMA_BUILDINGS) {
  for (const id of building.prismIds) materials.set(id, building);
}

export function potsdamerPanoramaMaterialFor(id: string): PotsdamerPanoramaMaterial | undefined {
  return materials.get(id);
}

// Upper metal/glass storeys in the near west-side blocks, as a visual height
// subdivision only. The source footprint, roof height and courts do not change.
const upperStoreyParents = new Set([
  "DEBE01YYK0002KZt", "DEBE01YYK0002M3M", "DEBE01YYK0002Kwp",
]);
const upperStoreyIds = new Set<string>(
  POTSDAMER_PANORAMA_BUILDINGS.filter(building => upperStoreyParents.has(building.parentId))
    .flatMap(building => [...building.prismIds]),
);
export const POTSDAMER_UPPER_STOREYS = { startM: 28.5, color: 0x8d989a } as const;
export function hasPotsdamerUpperStoreys(id: string, heightM: number): boolean {
  return heightM > POTSDAMER_UPPER_STOREYS.startM + 1 && upperStoreyIds.has(id);
}

